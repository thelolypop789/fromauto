-- เขตของฉัน + จำนวนคนในแอปที่ลงเขตเดียวกัน (ซ่อนตัวเลขถ้าน้อยกว่า 5 คน) + ควรถามไหม
create or replace function public.prep_my_area() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  u uuid := prep.uid();
  p prep.profiles;
  k text;
  same int; same_major int;
begin
  if u is null then raise exception 'not_authenticated'; end if;
  select * into p from prep.profiles where user_id = u;
  if p.user_id is null then return null; end if;
  if p.area_code is null then
    return jsonb_build_object('code', null, 'kind', null, 'label', null,
      'ask', p.area_snooze_until is null or p.area_snooze_until < now());
  end if;
  select kind into k from prep.exam_areas where code = p.area_code;
  if k = 'none' then return jsonb_build_object('code', 'none', 'kind', 'none', 'label', 'ไม่ได้สมัครรอบนี้', 'ask', false); end if;
  select count(*), count(*) filter (where p.major is not null and x.major = p.major) into same, same_major
    from prep.profiles x where x.area_code = p.area_code;
  return jsonb_build_object('code', p.area_code, 'kind', k, 'label', p.area_code, 'ask', false,
    'same', case when same >= 5 then same end,
    'same_major', case when same_major >= 5 then same_major end);
end $$;


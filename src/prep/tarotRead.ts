function trend(v: number[]): Trend {
  const c = v.map(cls);
  if (c.every(x => x === "good")) return "high";
  if (!c.includes("good") && c.filter(x => x === "bad").length >= 2) return "low";
  if (v[2] > v[0] && v[1] >= v[0]) return "rise";
  if (v[2] < v[0] && v[1] <= v[0]) return "fall";
  return "mixed";
}

// ดวงรวมจากค่าดวงของไพ่ 3 ใบ (ไพ่อนาคตมีน้ำหนักเป็น 2 เท่า) ช่วงค่า -8 … +8
export function overall(score: number): { t: string; d: string } {
  if (score >= 5) return { t: "ดวงสอบรุ่งพุ่งแรง 🌟", d: "ความพยายามของคุณกำลังจะออกดอกออกผล" };
  if (score >= 2) return { t: "ดวงดี มีลุ้น ✨", d: "ไพ่ส่วนใหญ่เป็นใจ เติมจุดที่ไพ่เตือนแล้วดวงจะเปิดเต็มที่" };
  if (score >= -1) return { t: "ดวงกลาง ๆ ขึ้นกับความเพียร 💪", d: "ผลยังไม่แน่นอน วันที่เหลือคือตัวตัดสิน" };
  return { t: "ไพ่เตือนให้เตรียมตัวหนักขึ้น ⚠️", d: "ตอนนี้ยังไม่พร้อมพอ ต้องเพิ่มเวลาฝึกอย่างจริงจัง" };
}
export const cardScore = (picks: Pick[]) => picks.reduce((s, p, i) => s + val(p) * (i === 2 ? 2 : 1), 0);

// Joins "…บอกว่า" with a card paragraph. A paragraph that opens with the card's own verb ("ไพ่เตือนว่า…", "นี่คือไพ่…")
// takes that verb instead, so it never reads "…บอกว่าไพ่เตือนว่า…".
const OPENERS: [RegExp, string][] = [
  [/^ตอนนี้ไพ่เตือน/, "เตือน"], [/^ไพ่เตือนหนัก/, "เตือนหนัก"], [/^ไพ่เตือน/, "เตือน"], [/^นี่คือ/, "คือ"],
];
function say(lead: string, text: string): string {
  for (const [re, verb] of OPENERS) if (re.test(text)) return lead.replace(/บอกว่า$/, verb) + text.replace(re, "");
  return lead + text;
}

export type Reading = { paras: string[]; pair: string | null; trend: { t: string; d: string }; verdict: { t: string; d: string } };

export function readCards(picks: Pick[]): Reading {
  const [a, b, c] = picks;
  const v = picks.map(val), k = v.map(cls);
  const short = (p: Pick) => CARDS[p.c].en + (p.r ? " ที่กลับหัว" : "");
  const fill = (s: string) => s.replace("{a}", short(a)).replace("{b}", cardName(b)).replace("{c}", cardName(c));
  const paras = [
    say(`ในตำแหน่งอดีต ${cardName(a)} บอกว่า`, CARDS[a.c][a.r ? "rev" : "up"][0]),
    say(fill(TO_NOW[k[0]][k[1]]), CARDS[b.c][b.r ? "rev" : "up"][1]),
    say(fill(TO_EXAM[k[1]][k[2]]), CARDS[c.c][c.r ? "rev" : "up"][2]),
  ];
  const order = picks.filter(p => !p.r).map(p => p.c);
  const hit = PAIRS.find(([x, y]) => { const i = order.indexOf(x), j = order.indexOf(y); return i >= 0 && j > i; });
  return { paras, pair: hit ? hit[2] : null, trend: TREND[trend(v)], verdict: overall(cardScore(picks)) };
}

#!/usr/bin/env node
// Builds hand-written major questions (content/prep/bank-major-*.json) into a SQL insert for prep.questions, each one
// labelled with its sub-topic (prep.subtopic_tags) so sub-topic practice and the mock blueprint pick it up.
// Each item is [sub, level, stem, [right, wrong, wrong, wrong], explanation]; sub is the code after the topic
// ("PINYIN" → B3-CHN-PINYIN) and level is r/u/a/n. The right answer is written first and the choices are shuffled here
// with a seed from the stem, so a re-run gives the same order (and the same content_hash: re-applying skips duplicates).
// Usage: node scripts/prep/gen_major_bank_sql.mjs supabase/migrations/<timestamp>_prep_major_bank.sql [files...]
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const [out, ...args] = process.argv.slice(2);
if (!out) { console.error("usage: gen_major_bank_sql.mjs <out.sql> [content/prep/bank-major-*.json ...]"); process.exit(1); }
const files = args.length ? args : readdirSync("content/prep").filter(f => /^bank-major-.+\.json$/.test(f)).sort().map(f => `content/prep/${f}`);

const LEVEL = { r: "remember", u: "understand", a: "apply", n: "analyze" };
const subs = new Set(JSON.parse(readFileSync("content/prep/major-subtopics.json", "utf8")).flatMap(m => m.subs.map(s => s.code)));
const q = s => "'" + String(s).replace(/'/g, "''") + "'";

function shuffle(choices, seed) {
  const order = [0, 1, 2, 3];
  let h = createHash("sha256").update(seed).digest();
  for (let i = 3; i > 0; i--) {
    const j = h[i] % (i + 1);
    [order[i], order[j]] = [order[j], order[i]];
  }
  return { choices: order.map(k => choices[k]), answer: order.indexOf(0) };
}

const rows = [];
const stems = new Set();
const answers = [0, 0, 0, 0];
for (const file of files) {
  const { topic, items } = JSON.parse(readFileSync(file, "utf8"));
  for (const [i, it] of items.entries()) {
    const [sub, lvl, stem, choices, explanation] = it;
    const code = `${topic}-${sub}`;
    const where = `${file} #${i + 1}`;
    if (!subs.has(code)) throw new Error(`${where}: unknown sub-topic ${code}`);
    if (!LEVEL[lvl]) throw new Error(`${where}: level must be r/u/a/n`);
    if (typeof stem !== "string" || stem.trim().length < 12) throw new Error(`${where}: stem too short`);
    if (!Array.isArray(choices) || choices.length !== 4 || new Set(choices.map(c => c.trim())).size !== 4 || choices.some(c => !c.trim()))
      throw new Error(`${where}: needs 4 distinct non-empty choices`);
    if (!explanation || explanation.length < 10) throw new Error(`${where}: explanation missing`);
    if (stems.has(stem.trim())) throw new Error(`${where}: duplicate stem`);
    stems.add(stem.trim());
    const s = shuffle(choices.map(c => c.trim()), stem);
    answers[s.answer]++;
    rows.push(`  (${q(topic)}, ${q(code)}, ${q(LEVEL[lvl])}, ${q(stem.trim())}, ${q(JSON.stringify(s.choices))}::jsonb, ${s.answer}, ${q(explanation)})`);
  }
}

const sql = `-- GENERATED by scripts/prep/gen_major_bank_sql.mjs from ${files.join(", ")} (do not edit by hand).
-- Hand-written major questions, published at once and labelled with their sub-topic. Questions already in the bank
-- (same content_hash) are skipped, so this file can be applied again.
with v (topic, subtopic, level, stem, choices, answer, explanation) as (values
${rows.join(",\n")}
), ins as (
  insert into prep.questions (topic, level, stem, choices, answer, explanation, origin, source, status, content_hash, subtopic)
  select v.topic, v.level, v.stem, v.choices, v.answer::smallint, v.explanation, 'ai', 'claude:authored', 'approved',
         prep.content_hash(v.stem, v.choices), v.subtopic
    from v
  on conflict (content_hash) do nothing
  returning id, subtopic
)
insert into prep.subtopic_tags (question_id, subtopic, confidence, source, model)
select id, subtopic, 1, 'ai', 'claude-authored' from ins;
`;
writeFileSync(out, sql);
console.log(`wrote ${out}: ${rows.length} questions from ${files.length} files · answer positions ${answers.join("/")}`);

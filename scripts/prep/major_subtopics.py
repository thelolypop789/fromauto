def build():
    root = pathlib.Path(__file__).resolve().parents[2]
    out = []
    for m in MAJORS:
        codes = [s["code"] for s in m["subs"]]
        assert len(codes) == len(set(codes)), m["topic"]
        total = sum(s["weight"] for s in m["subs"])
        for i, s in enumerate(m["subs"]):
            s["code"] = f'{m["topic"]}-{s["code"]}'
            s["sort"] = i + 1
        out.append({**m, "weight_total": total})
    (root / "content/prep/major-subtopics.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")

    md = ["# หมวดย่อยวิชาเอก (ตรวจกับหลักสูตรแกนกลางแล้ว)", "",
          "อ้างอิง: หลักสูตรแกนกลางการศึกษาขั้นพื้นฐาน พ.ศ. 2551 (ฉบับปรับปรุง พ.ศ. 2560) และหลักสูตรการศึกษาปฐมวัย พ.ศ. 2560",
          "", "น้ำหนัก = สัดส่วนข้อในข้อสอบจำลองวิชาเอก 100 ข้อ (ประมาณการ ปรับได้ในฐานข้อมูล) · เนื้อหา ≈ 75–85% ศาสตร์การสอน ≈ 15–25%", ""]
    for m in out:
        md += [f'## {m["name"]} (`{m["topic"]}`)', "", f'**หลักสูตรแกนกลาง:** {m["core"]}', ""]
        if m["changes"]:
            md += ["**ปรับจาก blueprint:**"] + [f"- {c}" for c in m["changes"]] + [""]
        md += ["| หมวดย่อย | ประเภท | ข้อโดยประมาณ (จาก 100) |", "|---|---|---|"]
        for s in m["subs"]:
            md.append(f'| {s["name"]} | {"เนื้อหา" if s["kind"] == C else "ศาสตร์การสอน"} | {round(100 * s["weight"] / m["weight_total"])} |')
        md.append("")
    md += ["## วิชาเอกที่ยังไม่แยกหมวด", "", "- ธุรกิจและพาณิชยกรรม (`B3-BUS`), บรรณารักษ์ (`B3-LIB`): ไม่อยู่ใน blueprint ยังเป็นหมวดเดียว", ""]
    (root / "docs/prep-major-blueprint.md").write_text("\n".join(md))

    if "--sql" in sys.argv:
        stamp = sys.argv[sys.argv.index("--sql") + 1]
        q = lambda s: "'" + s.replace("'", "''") + "'"
        rows = [f'  ({q(s["code"])}, {q(m["topic"])}, {q(s["name"])}, {q(s["kind"])}, {s["weight"]}, {s["sort"]}, {q(s["desc"])})'
                for m in out for s in m["subs"]]
        sql = ("-- Generated by scripts/prep/major_subtopics.py from the major blueprint (checked against the core curriculum).\n"
               "insert into prep.subtopics (code, topic, name, kind, weight, sort, keywords) values\n" + ",\n".join(rows) +
               "\non conflict (code) do update set topic = excluded.topic, name = excluded.name, kind = excluded.kind,\n"
               "  weight = excluded.weight, sort = excluded.sort, keywords = excluded.keywords;\n")
        (root / f"supabase/migrations/{stamp}_prep_major_subtopics_seed.sql").write_text(sql)
    print(len(out), "majors,", sum(len(m["subs"]) for m in out), "subtopics")
    for m in out: print(f'  {m["topic"]:12} {len(m["subs"]):2} subs  weight {m["weight_total"]}')

if __name__ == "__main__":
    build()

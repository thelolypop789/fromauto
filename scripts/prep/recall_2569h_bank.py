"""แนวข้อสอบ ครูผู้ช่วย สพฐ. รอบทั่วไป 2569 (ภาค ก, 14 พ.ย. 2569) จากผู้เข้าสอบ — ชุด h

ที่มา: คอมเมนต์ผู้เข้าสอบที่ผู้ใช้ส่งภาพมา (เรียกว่า "แนวข้อสอบ" เสมอ) — เขียนใหม่เป็นสถานการณ์ หาเฉลยเองจาก ม.13 พ.ร.บ.วิธีปฏิบัติราชการทางปกครอง
คลังมีข้อหลักการทั่วไปอยู่แล้ว (#1242 ลักษณะต้องห้าม, #1644 เป็นเพื่อนคู่กรณีพิจารณาได้) ข้อนี้เป็นฉบับสถานการณ์ตามที่ออกสอบ
python3 scripts/prep/recall_2569h_bank.py → content/prep/bank-recall-2569h.json
"""
import json
import random
from pathlib import Path

from bankkit import Bank

ROOT = Path(__file__).resolve().parents[2]
TAG = "แนวข้อสอบ ครูผู้ช่วย สพฐ. รอบทั่วไป 2569 (จากผู้เข้าสอบ)"
b = Bank(seed=256921)

b.add("A3-ADMINPROC", "apply",
      "ครูผู้ช่วยคนหนึ่งได้รับแต่งตั้งเป็นกรรมการสอบสวนข้าราชการครูคนหนึ่ง กรณีใดที่ครูผู้ช่วยคนนี้ไม่อาจทำหน้าที่สอบสวนเรื่องนั้นได้",
      "เป็นลูกหนี้ของครูที่ถูกสอบสวน",
      ["อายุน้อยกว่าครูที่ถูกสอบสวน", "เป็นเพื่อนร่วมงานของครูที่ถูกสอบสวน", "เคยจดรายงานการประชุมของโรงเรียน"],
      "พ.ร.บ.วิธีปฏิบัติราชการทางปกครอง พ.ศ. 2539 มาตรา 13 ห้ามเจ้าหน้าที่หรือกรรมการพิจารณาทางปกครองในเรื่องที่ตนเป็นคู่กรณีเอง "
      "เป็นคู่หมั้นหรือคู่สมรส เป็นญาติ เป็นหรือเคยเป็นผู้แทนหรือตัวแทนของคู่กรณี หรือเป็นเจ้าหนี้ ลูกหนี้ หรือนายจ้างของคู่กรณี "
      "การเป็นลูกหนี้ของครูที่ถูกสอบสวนจึงทำหน้าที่ไม่ได้ ส่วนอายุ การเป็นเพื่อนร่วมงาน และการเคยจดรายงานการประชุม ไม่ใช่เหตุต้องห้ามตามกฎหมาย",
      law_ref="พ.ร.บ.วิธีปฏิบัติราชการทางปกครอง พ.ศ. 2539 ม.13")

OUT = ROOT / "content" / "prep" / "bank-recall-2569h.json"
out = b.build(OUT, TAG)
rng = random.Random(25691121)
for q in out:
    pos = rng.randrange(4)
    cor = q["choices"].pop(q["answer"])
    q["choices"].insert(pos, cor)
    q["answer"] = pos
    q["exam_tag"] = TAG
    q["source"] = "เรียบเรียงใหม่ · " + TAG
OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")

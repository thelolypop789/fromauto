    assert [n ** 3 + n ** 2 for n in range(1, 6)] == [2, 12, 36, 80, 150]
    assert [sum(k * k for k in range(1, n + 1)) for n in range(1, 6)] == [1, 5, 14, 30, 55]
    assert [2 ** n - 1 for n in range(1, 6)] == [1, 3, 7, 15, 31]
    del Fraction



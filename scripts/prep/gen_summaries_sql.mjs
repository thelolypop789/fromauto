#!/usr/bin/env node
// Builds the mind-map summaries (content/summaries/*.ts) into a SQL upsert for prep.summaries, so the app fetches each map
// through prep_summary_get (which checks the package) instead of shipping every map in the bundle.
// Usage: node scripts/prep/gen_summaries_sql.mjs supabase/migrations/<timestamp>_prep_summaries_content.sql
// Then apply that file. Approvals (prep.summary_approvals) are kept; a map that changes keeps its approval, so re-check it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const out = process.argv[2];
if (!out) { console.error("usage: gen_summaries_sql.mjs <out.sql>"); process.exit(1); }
const dir = mkdtempSync(join(tmpdir(), "summaries-"));
const js = join(dir, "maps.mjs");
execFileSync("npx", ["-y", "esbuild@0.24.0", "content/summaries/index.ts", "--bundle", "--format=esm", "--platform=node", `--outfile=${js}`], { stdio: "inherit" });
const { MAPS } = await import(js);
const ids = new Set();
for (const m of MAPS) {
  if (!/^[a-z0-9-]{1,60}$/.test(m.id) || ids.has(m.id)) throw new Error(`bad or duplicate id ${m.id}`);
  if (m.branches.length < 4 || m.branches.length > 6) throw new Error(`${m.id}: needs 4-6 branches`);
  // The list card takes its colour from the first branch (prep_summary_list), and every card is pink.
  if (m.branches[0].tone !== "pink") throw new Error(`${m.id}: first branch must be pink`);
  ids.add(m.id);
}
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const rows = MAPS.map((m, i) => `  (${q(m.id)}, ${q(m.group)}, ${m.free ? "true" : "false"}, ${i}, ${q(JSON.stringify(m))}::jsonb)`);
const sql = `-- GENERATED by scripts/prep/gen_summaries_sql.mjs from content/summaries (do not edit by hand).
insert into prep.summaries (id, grp, free, sort, data) values
${rows.join(",\n")}
on conflict (id) do update set grp = excluded.grp, free = excluded.free, sort = excluded.sort, data = excluded.data, updated_at = now();
delete from prep.summaries where id not in (${[...ids].map(q).join(", ")});
`;
writeFileSync(out, sql);
console.log(`wrote ${out}: ${MAPS.length} maps, ${readFileSync(out).length} bytes`);

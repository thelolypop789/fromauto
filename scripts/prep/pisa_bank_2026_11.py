def build():
    rng = random.Random(20261105)
    out = []
    for topic in (D, W, R):
        items = [q for q in Q if q["topic"] == topic]
        slots = [i % 4 for i in range(len(items))]
        rng.shuffle(slots)
        for q, pos in zip(items, slots):
            ch = [LONGER.get(w, w) for w in q["wrong"]]
            assert q["correct"] not in ch
            rng.shuffle(ch)
            ch.insert(pos, q["correct"])
            out.append(dict(topic=topic, subtopic=None, level=q["level"], stem=q["stem"], choices=ch, answer=pos,
                            explanation=q["explanation"], law_ref=None, ref=REF, source="claude:authored", status="review"))
    stems = [q["stem"] for q in out]
    assert len(stems) == len(set(stems))
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
    print(len(out), dict(Counter(q["topic"] for q in out)))
    for t in (D, W, R):
        print(t, sorted(Counter(q["answer"] for q in out if q["topic"] == t).items()))
    print("correct is the longest:", sum(1 for q in out if max(range(4), key=lambda i: len(q["choices"][i])) == q["answer"]), "of", len(out))


if __name__ == "__main__":
    build()

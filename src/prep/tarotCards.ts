  if (score >= -1) return { t: "ดวงกลาง ๆ ขึ้นกับความเพียร 💪", d: "ไพ่บอกว่าผลยังไม่แน่นอน {d} วันที่เหลือคือตัวตัดสิน ยิ่งฝึก โอกาสยิ่งมาก อย่าปล่อยให้เวลาหลุดมือ" };

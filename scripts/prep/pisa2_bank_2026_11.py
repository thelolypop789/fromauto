    out = []
    for topic in (P, RA, SE, AN, CV):
        items = [q for q in Q if q["topic"] == topic]
        slots = [i % 4 for i in range(len(items))]
        rng.shuffle(slots)
        for q, pos in zip(items, slots):
            ch = [LONGER.get(w, w) for w in q["wrong"]]

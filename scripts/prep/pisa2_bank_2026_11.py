    rules = [
        lambda: 23 + 10, lambda: 36 + 12, lambda: 244 * 3 - 2, lambda: 19 + 16, lambda: 35 + 32, lambda: 120 * 6, lambda: 13 ** 2, lambda: 5 + 8,
        lambda: 8, lambda: 50 - 25, lambda: 28 - 2, lambda: 6 ** 3, lambda: 240 * 6, lambda: 37 + 15, lambda: 31 * 2 + 1, lambda: 29 + 10,
        lambda: "1/3", lambda: 20.25 * 1.5, lambda: 16 + 6, lambda: 6 ** 3 + 6 ** 2, lambda: 33 + 25, lambda: 127 * 2 + 1, lambda: 4, lambda: 56 + 25,
        lambda: 48 * 5, lambda: 6 ** 2 - 1, lambda: 22 + 5, lambda: 55 + 36]
    assert len(rules) == len(SERIES)
    for (seq, ans, wrong, why), r in zip(SERIES, rules):
        assert r() == ans, (seq, ans, r())
        assert ans not in wrong
    # ตรวจลำดับที่ให้มาสอดคล้องกับกติกาบางข้อที่ตรวจด้วยสูตรได้
